import Foundation
import Security

/// Minimal Keychain wrapper for API keys and access tokens.
/// Items are device-only and unavailable while the phone is locked.
enum KeychainStore {
    private static let service = "de.hsd-hamburg.UniMessenger"

    static func set(_ value: String?, for key: String) {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: key,
        ]
        SecItemDelete(query as CFDictionary)
        guard let value, !value.isEmpty else { return }
        var item = query
        item[kSecValueData as String] = Data(value.utf8)
        item[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
        SecItemAdd(item as CFDictionary, nil)
    }

    static func get(_ key: String) -> String? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: key,
            kSecReturnData as String: true,
            kSecMatchLimit as String: kSecMatchLimitOne,
        ]
        var result: AnyObject?
        guard SecItemCopyMatching(query as CFDictionary, &result) == errSecSuccess,
              let data = result as? Data else { return nil }
        return String(data: data, encoding: .utf8)
    }

    enum Key {
        static let anthropicAPIKey = "anthropic.apiKey"
        static func secret(_ account: UUID) -> String { "account.\(account.uuidString).secret" }
        static func token(_ account: UUID) -> String { "account.\(account.uuidString).token" }
    }
}
